-- Phase 9: audit trail for administrative operations (approve/reject quotes, reconcile). Append-only.
CREATE TABLE admin_audit (
    audit_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      varchar(64)  NOT NULL,
    user_id        varchar(128) NOT NULL,
    action         varchar(64)  NOT NULL,
    target         varchar(128) NOT NULL DEFAULT '',
    outcome        varchar(16)  NOT NULL CHECK (outcome IN ('Succeeded','Rejected','Failed')),
    detail         varchar(300) NOT NULL DEFAULT '',
    correlation_id varchar(64)  NOT NULL DEFAULT '',
    occurred_at    timestamptz  NOT NULL
);
CREATE INDEX ix_admin_audit_tenant_time ON admin_audit (tenant_id, occurred_at DESC);
