-- Phase 8 (CRM side): read-only mirrors of ERP fulfilment facts, plus the CRM-owned return request.
-- ERP owns shipments/invoices/payments; rows here are upserted by Temporal activities, keyed by the ERP id, and only
-- ever move forward (version must increase) so duplicate or out-of-order deliveries cannot regress state.
CREATE TABLE shipments (
    tenant_id        varchar(64)  NOT NULL,
    erp_shipment_id  varchar(64)  NOT NULL,
    quote_id         integer      NOT NULL REFERENCES quotes (quote_id),
    erp_order_id     varchar(64)  NOT NULL,
    status           varchar(20)  NOT NULL CHECK (status IN ('Packed','Shipped','InTransit','Delivered','Cancelled')),
    carrier          varchar(100) NOT NULL DEFAULT '',
    tracking_number  varchar(100) NOT NULL DEFAULT '',
    version          integer      NOT NULL CHECK (version > 0),
    updated_at       timestamptz  NOT NULL,
    PRIMARY KEY (tenant_id, erp_shipment_id)
);
CREATE INDEX ix_shipments_quote ON shipments (tenant_id, quote_id);

CREATE TABLE invoices (
    tenant_id        varchar(64)   NOT NULL,
    erp_invoice_id   varchar(64)   NOT NULL,
    quote_id         integer       NOT NULL REFERENCES quotes (quote_id),
    customer_id      integer       NOT NULL REFERENCES customers (customer_id),
    erp_order_id     varchar(64)   NOT NULL,
    number           varchar(64)   NOT NULL,
    total            numeric(14,2) NOT NULL CHECK (total >= 0),
    status           varchar(20)   NOT NULL CHECK (status IN ('Issued','PartiallyPaid','Paid','Overdue','Void')),
    issued_at        timestamptz   NOT NULL,
    due_at           timestamptz,
    version          integer       NOT NULL CHECK (version > 0),
    updated_at       timestamptz   NOT NULL,
    PRIMARY KEY (tenant_id, erp_invoice_id)
);
CREATE INDEX ix_invoices_quote ON invoices (tenant_id, quote_id);
CREATE INDEX ix_invoices_customer ON invoices (tenant_id, customer_id);

CREATE TABLE payments (
    tenant_id        varchar(64)   NOT NULL,
    erp_payment_id   varchar(64)   NOT NULL,
    erp_invoice_id   varchar(64)   NOT NULL,
    quote_id         integer       NOT NULL REFERENCES quotes (quote_id),
    amount           numeric(14,2) NOT NULL CHECK (amount >= 0),
    status           varchar(20)   NOT NULL CHECK (status IN ('Received','Reconciled','Reversed')),
    version          integer       NOT NULL CHECK (version > 0),
    updated_at       timestamptz   NOT NULL,
    PRIMARY KEY (tenant_id, erp_payment_id)
);
CREATE INDEX ix_payments_quote ON payments (tenant_id, quote_id);

-- Return requests are owned by the CRM; the ERP authorises them (stock/financial adjustment is ERP-side).
CREATE TABLE return_requests (
    return_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      varchar(64)  NOT NULL,
    quote_id       integer      NOT NULL REFERENCES quotes (quote_id),
    customer_id    integer      NOT NULL REFERENCES customers (customer_id),
    status         varchar(20)  NOT NULL CHECK (status IN ('Requested','Authorized','Rejected','Completed')),
    reason         varchar(500) NOT NULL,
    erp_return_id  varchar(64)  NOT NULL DEFAULT '',
    decision_note  varchar(500) NOT NULL DEFAULT '',
    requested_by   varchar(128) NOT NULL,
    created_at     timestamptz  NOT NULL,
    updated_at     timestamptz  NOT NULL
);
CREATE INDEX ix_returns_quote ON return_requests (tenant_id, quote_id);
CREATE UNIQUE INDEX ux_returns_tenant_erp ON return_requests (tenant_id, erp_return_id) WHERE erp_return_id <> '';

CREATE TABLE return_request_lines (
    return_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      varchar(64) NOT NULL,
    return_id      integer     NOT NULL REFERENCES return_requests (return_id),
    sku            varchar(64) NOT NULL,
    quantity       integer     NOT NULL CHECK (quantity > 0)
);
CREATE INDEX ix_return_lines_return ON return_request_lines (tenant_id, return_id);
