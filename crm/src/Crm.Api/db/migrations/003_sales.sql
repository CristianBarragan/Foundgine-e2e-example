CREATE TABLE opportunities (
    opportunity_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   varchar(64)   NOT NULL,
    customer_id integer       NOT NULL REFERENCES customers (customer_id),
    name        varchar(200)  NOT NULL,
    stage       varchar(20)   NOT NULL CHECK (stage IN ('Prospecting','Qualification','Proposal','Negotiation','ClosedWon','ClosedLost')),
    amount      numeric(14,2) NOT NULL DEFAULT 0,
    created_at  timestamptz   NOT NULL,
    created_by  varchar(128)  NOT NULL,
    updated_at  timestamptz   NOT NULL,
    updated_by  varchar(128)  NOT NULL
);
CREATE INDEX ix_opportunities_tenant_customer ON opportunities (tenant_id, customer_id);

CREATE TABLE quotes (
    quote_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      varchar(64)   NOT NULL,
    opportunity_id integer       NOT NULL REFERENCES opportunities (opportunity_id),
    customer_id    integer       NOT NULL REFERENCES customers (customer_id),
    status         varchar(20)   NOT NULL CHECK (status IN ('Draft','PendingApproval','Approved','Rejected','Accepted','Ordered')),
    total          numeric(14,2) NOT NULL DEFAULT 0,
    submitted_by   varchar(128)  NOT NULL DEFAULT '',
    decided_by     varchar(128)  NOT NULL DEFAULT '',
    erp_order_id   varchar(64)   NOT NULL DEFAULT '',
    created_at     timestamptz   NOT NULL,
    created_by     varchar(128)  NOT NULL,
    updated_at     timestamptz   NOT NULL,
    updated_by     varchar(128)  NOT NULL
);
CREATE INDEX ix_quotes_tenant_customer ON quotes (tenant_id, customer_id);
CREATE UNIQUE INDEX ux_quotes_tenant_erp_order ON quotes (tenant_id, erp_order_id) WHERE erp_order_id <> '';

CREATE TABLE quote_lines (
    quote_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     varchar(64)   NOT NULL,
    quote_id      integer       NOT NULL REFERENCES quotes (quote_id),
    sku           varchar(64)   NOT NULL,
    description   varchar(300)  NOT NULL DEFAULT '',
    quantity      integer       NOT NULL CHECK (quantity > 0),
    unit_price    numeric(14,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX ix_quote_lines_quote ON quote_lines (tenant_id, quote_id);
