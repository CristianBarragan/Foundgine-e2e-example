CREATE TABLE customers (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   varchar(64)  NOT NULL,
    kind        varchar(16)  NOT NULL CHECK (kind IN ('Business', 'Individual')),
    name        varchar(200) NOT NULL,
    email       varchar(320) NOT NULL,
    phone       varchar(50)  NOT NULL DEFAULT '',
    status      varchar(16)  NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    created_at  timestamptz  NOT NULL,
    created_by  varchar(128) NOT NULL,
    updated_at  timestamptz  NOT NULL,
    updated_by  varchar(128) NOT NULL
);
CREATE INDEX ix_customers_tenant_name ON customers (tenant_id, name);
CREATE UNIQUE INDEX ux_customers_tenant_email ON customers (tenant_id, lower(email));

CREATE TABLE contacts (
    contact_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   varchar(64)  NOT NULL,
    customer_id integer      NOT NULL REFERENCES customers (customer_id),
    first_name  varchar(100) NOT NULL,
    last_name   varchar(100) NOT NULL,
    email       varchar(320) NOT NULL,
    phone       varchar(50)  NOT NULL DEFAULT '',
    is_primary  boolean      NOT NULL DEFAULT false,
    created_at  timestamptz  NOT NULL,
    created_by  varchar(128) NOT NULL,
    updated_at  timestamptz  NOT NULL,
    updated_by  varchar(128) NOT NULL
);
CREATE INDEX ix_contacts_tenant_customer ON contacts (tenant_id, customer_id);
